"""Score an agent on the open-source js13k test set: a stand-in for the private leaderboard.

The private 16 games are unseen, so we measure generalisation on games the agent was never
tuned on: 54 js13kGames jam entries packaged by alexchilton on Kaggle
(alexchilton/gga-open-jam-games-test-set; scripts/setup_jam.sh puts it in data/jam).
Each scored game has an idle value and a reference value (the best of random and fixed-key
policies over 2 minutes, not a human), and we normalise like the host does:
clip((best - idle) / (reference - idle), 0, 1). Only non-trivial scored games count by default.

The dataset's own tools are not run. We read its game list (games_extra.json) as data and
take its score readers out of tools/extra_games.py by parsing the source (ast, no execution);
then build/jam/ is assembled like eval/harness.py does for the sample games: the dataset's
gga package, with a generated readers package, and the jam games as games.json and assets/.

    python eval/jam.py                                  # agent/agent.py, all non-trivial scored games
    python eval/jam.py --agent other.py --jobs 3 --minutes 1 --tag quick
    python eval/jam.py --games roads,pulse --env GGA_MODEL=mock
    python eval/jam.py --list

Results: runs/jam/<tag>/<game>.json per game and summary.json; the table goes to stdout.
"""
from __future__ import annotations

import argparse
import ast
import json
import os
import shutil
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "gga"
JAM = ROOT / "data" / "jam"
EXTRA = JAM / "data" / "extra_games"
BUILD = ROOT / "build" / "jam"
BROWSERS = DATA / "kit" / "browsers"


# -- readers, read out of the dataset's source without running it -------------------------------
class _Eval(ast.NodeVisitor):
    """Literal values, plus f-strings and names that refer to module-level string constants."""

    def __init__(self, names: dict[str, str]):
        self.names = names

    def value(self, node):
        if isinstance(node, ast.Constant):
            return node.value
        if isinstance(node, ast.Name) and node.id in self.names:
            return self.names[node.id]
        if isinstance(node, ast.JoinedStr):
            return "".join(self.value(v) for v in node.values)
        if isinstance(node, ast.FormattedValue):
            if node.format_spec is not None or node.conversion != -1:
                raise ValueError("unsupported f-string field")
            return str(self.value(node.value))
        if isinstance(node, (ast.Tuple, ast.List)):
            return tuple(self.value(e) for e in node.elts)
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
            return self.value(node.left) + self.value(node.right)
        raise ValueError(f"unsupported node {type(node).__name__} at line {getattr(node, 'lineno', '?')}")


def reader_specs(source: Path) -> dict[str, dict]:
    """{game: {path, body, note, replace, html, more}} from the _reader(...) calls in the source."""
    tree = ast.parse(source.read_text(), filename=str(source))
    names: dict[str, str] = {}
    ev = _Eval(names)
    specs: dict[str, dict] = {}
    for stmt in tree.body:
        if (isinstance(stmt, ast.Assign) and len(stmt.targets) == 1 and isinstance(stmt.targets[0], ast.Name)
                and stmt.targets[0].id.startswith("_") and isinstance(stmt.value, ast.Constant)
                and isinstance(stmt.value.value, str)):
            names[stmt.targets[0].id] = stmt.value.value
        call = stmt.value if isinstance(stmt, ast.Expr) else None
        if not (isinstance(call, ast.Call) and isinstance(call.func, ast.Name) and call.func.id == "_reader"):
            continue
        args = [ev.value(a) for a in call.args]
        kw = {k.arg: ev.value(k.value) for k in call.keywords}
        game, path, body, note = args[:4]
        specs[game] = {"path": path, "body": body, "note": note, "replace": kw.get("replace", ()),
                       "html": bool(kw.get("html", False)), "more": kw.get("more", ())}
    return specs


READERS_INIT = '''"""Generated by eval/jam.py: score readers for the jam games (see readers.json)."""
import hashlib
import json
from pathlib import Path

from gga.spec import ASSETS
from gga.state import Hook, Reader, reader_js


def _sha(p):
    return hashlib.sha256((ASSETS / p).read_bytes()).hexdigest()


def _build(game, s):
    js = reader_js(s["body"])
    first = Hook(path=s["path"], sha256=_sha(s["path"]), replace=tuple(tuple(r) for r in s["replace"]),
                 append=f"<script>{js}</script>" if s["html"] else js)
    more = tuple(Hook(path=p, sha256=_sha(p), replace=tuple(tuple(x) for x in r)) for p, r in s["more"])
    return Reader(game=game, hooks=(first, *more), note=s["note"])


READERS = {g: _build(g, s) for g, s in json.loads((Path(__file__).parent / "readers.json").read_text()).items()}
'''


