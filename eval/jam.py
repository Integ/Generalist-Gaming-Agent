def games() -> dict[str, dict]:
    return json.loads((EXTRA / "games_extra.json").read_text())["games"]


def prepare() -> Path:
    """build/jam: the dataset's harness, the jam games as games.json + assets/, generated readers."""
    if not (EXTRA / "games_extra.json").exists():
        sys.exit("data/jam missing: run scripts/setup_jam.sh")
    if BUILD.exists():
        shutil.rmtree(BUILD)
    BUILD.mkdir(parents=True)
    for item in DATA.iterdir():
        if item.name not in ("gga", "games.json", "assets", "assets.sha256"):
            (BUILD / item.name).symlink_to(item.resolve())
    (BUILD / "assets").symlink_to(EXTRA.resolve())
    shutil.copy(EXTRA / "games_extra.json", BUILD / "games.json")
    shutil.copytree(DATA / "gga", BUILD / "gga", ignore=shutil.ignore_patterns("readers", "__pycache__"))
    rd = BUILD / "gga" / "readers"
    rd.mkdir()
    (rd / "pause.py").write_text(PAUSE)
    (rd / "readers.json").write_text(json.dumps(reader_specs(JAM / "tools" / "extra_games.py"), indent=1))
    (rd / "__init__.py").write_text(READERS_INIT)
    return BUILD


# -- scoring --------------------------------------------------------------------------------------
def normalise(spec: dict, raw: float | None) -> float | None:
    sc = spec.get("scoring") or {}
    idle, ref = sc.get("idle"), sc.get("reference")
    if raw is None or idle is None or ref is None or ref <= idle:
        return None
    return min(1.0, max(0.0, (raw - idle) / (ref - idle)))


def run_one(game: str, agent: Path, minutes: float | None, env: dict, out: Path) -> dict:
    cmd = [sys.executable, "-m", "gga.game", "--game", game, "--agent", str(agent)]
    if minutes:
        cmd += ["--minutes", str(minutes)]
    t0 = time.time()
    with open(out / f"{game}.err", "w") as err:
        done = subprocess.run(cmd, cwd=BUILD, stdout=subprocess.PIPE, stderr=err, text=True,
                              env={**os.environ, "GGA_HEADLESS": "1", "PLAYWRIGHT_BROWSERS_PATH": str(BROWSERS),
                                   **env})
    lines = [line for line in done.stdout.splitlines() if line.startswith("{")]
    row = json.loads(lines[-1]) if lines else {"game": game, "status": f"no result (exit {done.returncode})"}
    row["wall_s"] = round(time.time() - t0, 1)
    (out / f"{game}.json").write_text(json.dumps(row))
    return row


def raw_of(row: dict) -> float | None:
    reading = row.get("reading") or {}
    v = reading.get("best_value", reading.get("value"))
    return None if v is None else float(v)


def default_games(all_games: dict, include_trivial: bool) -> list[str]:
    """Non-trivial scored games, minus any that are also competition games (off_line is a sample)."""
    official = set(json.loads((DATA / "games.json").read_text())["games"])
    return [g for g, s in all_games.items()
            if g not in official and normalise(s, (s.get("scoring") or {}).get("reference")) is not None
            and (include_trivial or not s.get("trivial"))]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--agent", default=str(ROOT / "agent" / "agent.py"))
    ap.add_argument("--games", help="comma list; default every non-trivial scored game")
    ap.add_argument("--include-trivial", action="store_true")
    ap.add_argument("--minutes", type=float, help="game minutes each; default the game's own (2)")
    ap.add_argument("--jobs", type=int, default=2, help="browsers at a time")
    ap.add_argument("--tag")
    ap.add_argument("--env", action="append", default=[], help="KEY=VALUE for the agent process")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--data", help="competition data root (default data/gga)")
    ap.add_argument("--jam", help="jam dataset root (default data/jam)")
    ap.add_argument("--build", help="where to assemble the harness (default build/jam)")
    ap.add_argument("--browsers", help="Playwright browsers (default <data>/kit/browsers)")
    ap.add_argument("--out", help="results directory (default runs/jam/<tag>)")
    a = ap.parse_args()
    global DATA, JAM, EXTRA, BUILD, BROWSERS
    if a.data:
        DATA = Path(a.data)
    if a.jam:
        JAM = Path(a.jam)
        EXTRA = JAM / "data" / "extra_games"
    if a.build:
        BUILD = Path(a.build)
    BROWSERS = Path(a.browsers) if a.browsers else DATA / "kit" / "browsers"

    all_games = games()
    chosen = a.games.split(",") if a.games else default_games(all_games, a.include_trivial)
    if a.list:
        for g in chosen:
            s = all_games[g]
            print(f"{g:28} {s['genre']:11} idle={s['scoring']['idle']:<6g} ref={s['scoring']['reference']:<8g} "
                  f"{s['title']}")
        print(f"{len(chosen)} games")
        return
    bad = [g for g in chosen if g not in all_games]
    if bad:
        sys.exit(f"unknown games: {bad}")
    prepare()
    agent = Path(a.agent).resolve()
    env = dict(e.split("=", 1) for e in a.env)
    tag = a.tag or time.strftime("%Y%m%d-%H%M%S") + "_" + agent.stem
    out = Path(a.out) if a.out else ROOT / "runs" / "jam" / tag
    out.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    with ThreadPoolExecutor(max(1, a.jobs)) as pool:
        rows = list(pool.map(lambda g: run_one(g, agent, a.minutes or all_games[g].get("minutes"), env, out), chosen))

    result = []
    print(f"{'game':28} {'genre':11} {'status':10} {'raw':>9} {'norm':>6}")
    for g, row in zip(chosen, rows):
        raw = raw_of(row)
        n = normalise(all_games[g], raw)
        result.append({"game": g, "genre": all_games[g]["genre"], "status": row.get("status"), "raw": raw, "norm": n})
        print(f"{g:28} {all_games[g]['genre']:11} {str(row.get('status', '?'))[:10]:10} "
              f"{'-' if raw is None else format(raw, 'g'):>9} {'n/a' if n is None else format(n, '.3f'):>6}")
    got = [r["norm"] for r in result if r["norm"] is not None]
    mean = sum(got) / len(got) if got else float("nan")
    summary = {"agent": str(agent), "env": env, "minutes": a.minutes, "mean": mean, "scored": len(got),
               "games": len(chosen), "wall_s": round(time.time() - t0), "rows": result}
    (out / "summary.json").write_text(json.dumps(summary, indent=1))
    print(f"mean normalised over {len(got)} of {len(chosen)} games: {mean:.4f}   "
          f"({summary['wall_s']} s, {out})")


if __name__ == "__main__":
    main()
